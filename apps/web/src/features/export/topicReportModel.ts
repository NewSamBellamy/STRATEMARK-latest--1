/**
 * The topic-based company report as data: what the screen, the PDF, the
 * Markdown file and the JSON file all render. One place numbers the footnotes,
 * so a source cited as [2] on screen is [2] in the PDF and the Markdown too.
 *
 * Integrity (AGENTS.md Rule 9): the report's text and figures come from the
 * engine; nothing here adds, rounds or fills a figure. A section with no
 * usable source says so, and an unmeasured cost is shown as not measured,
 * never as zero.
 */
import { REPORT_TOPIC_LABELS, usableCitations, type Citation, type Report, type ReportCost, type ReportSection, type ReportTopic } from '@mi/contracts';
import { exportSource, localDate } from './exportModel';

/** A real picture tied to its source: nothing here is generated. */
export interface ReportImage {
  src: string;
  /** Who made it, shown as the caption credit. */
  credit: string;
  /** The page the picture came from. */
  sourceUrl: string;
  kind: 'cover' | 'screenshot';
}

export interface ReportFootnote {
  n: number;
  title: string;
  url: string;
  direct: boolean;
}

export interface TopicReportSectionModel {
  topic: ReportTopic;
  title: string;
  markdown: string;
  footnotes: ReportFootnote[];
  gaps: string[];
  researchedDeeper: boolean;
  images: ReportImage[];
}

export interface ReportCompanyInfo {
  name: string;
  logoUrl: string | null;
  website: string | null;
  hq: string | null;
}

export interface TopicReportModel {
  id: string;
  title: string;
  company: ReportCompanyInfo;
  dateText: string;
  sections: TopicReportSectionModel[];
  /** Plain-words cost line, or null when the report predates cost tracking. */
  costLine: string | null;
  /** Sections where the stored research was thin and nothing more was found. */
  openGapCount: number;
  demo: boolean;
  /** The lead picture for the cover: the first publisher cover image found. It is taken out of its section so it is not shown twice. */
  hero: ReportImage | null;
}

export function costLine(cost: ReportCost | undefined | null): string | null {
  if (!cost) return null;
  if (cost.estUsd == null && cost.calls == null && cost.searches == null) return 'Cost to build: not measured';
  const parts: string[] = [];
  if (cost.estUsd != null) parts.push(`about $${cost.estUsd < 0.01 ? '0.01' : cost.estUsd.toFixed(2)} (estimate)`);
  if (cost.calls != null) parts.push(`${cost.calls} model ${cost.calls === 1 ? 'call' : 'calls'}`);
  if (cost.searches != null) parts.push(`${cost.searches} ${cost.searches === 1 ? 'search' : 'searches'}`);
  return `Cost to build: ${parts.join(', ')}`;
}

function footnotesFor(citations: readonly Citation[]): ReportFootnote[] {
  const seen = new Set<string>();
  const out: ReportFootnote[] = [];
  for (const c of usableCitations([...citations])) {
    if (seen.has(c.url)) continue;
    seen.add(c.url);
    out.push({ n: out.length + 1, ...exportSource(c) });
  }
  return out;
}

export function buildTopicReportModel(
  report: Report,
  company: ReportCompanyInfo,
  images: ReadonlyMap<ReportTopic, ReportImage[]> = new Map(),
  now: Date = new Date(report.createdAt),
): TopicReportModel {
  const all = [...images.values()].flat();
  const hero = all.find((i) => i.kind === 'cover') ?? null;
  const sections = (report.sections ?? []).map((s: ReportSection): TopicReportSectionModel => ({
    topic: s.topic,
    title: s.title || REPORT_TOPIC_LABELS[s.topic],
    markdown: s.markdown,
    footnotes: footnotesFor(s.citations),
    gaps: s.gaps,
    researchedDeeper: s.researchedDeeper,
    images: (images.get(s.topic) ?? []).filter((i) => i !== hero),
  }));
  return {
    id: report.id,
    title: report.title,
    company,
    dateText: now.toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' }),
    sections,
    costLine: costLine(report.cost),
    openGapCount: sections.filter((s) => s.gaps.length > 0).length,
    demo: /\(demo\)\s*$/.test(report.title),
    hero,
  };
}

/** Markdown with the sources as footnotes under each section. */
export function topicReportToMarkdown(report: Report, company: ReportCompanyInfo): string {
  const model = buildTopicReportModel(report, company);
  const out: string[] = [`# ${model.title}`, '', `*Stratemark company report · ${localDate(new Date(report.createdAt))}*`, ''];
  for (const s of model.sections) {
    out.push(`## ${s.title}`, '', s.markdown.trim(), '');
    if (s.gaps.length > 0) out.push(`> Not found: ${s.gaps.join(' ')}`, '');
    if (s.researchedDeeper) out.push('> This section needed extra research beyond what was stored.', '');
    if (s.footnotes.length > 0) {
      out.push('Sources:', ...s.footnotes.map((f) => `${f.n}. [${f.title}](${f.url})`), '');
    }
  }
  if (model.costLine) out.push(`*${model.costLine}.*`, '');
  out.push('---', '*Generated by Stratemark. Every figure carries its source; where the research did not support one it says so.*', '');
  return out.join('\n');
}

/** Machine-readable copy: the same sections, with sources numbered as in the PDF. */
export function topicReportToJson(report: Report, company: ReportCompanyInfo): string {
  const model = buildTopicReportModel(report, company);
  return JSON.stringify(
    {
      id: report.id,
      title: report.title,
      company: { name: company.name, website: company.website, hq: company.hq },
      createdAt: report.createdAt,
      topics: report.topics ?? model.sections.map((s) => s.topic),
      sections: model.sections.map((s) => ({
        topic: s.topic,
        title: s.title,
        markdown: s.markdown,
        gaps: s.gaps,
        researchedDeeper: s.researchedDeeper,
        sources: s.footnotes.map((f) => ({ n: f.n, title: f.title, url: f.url })),
      })),
      cost: report.cost ?? null,
    },
    null,
    2,
  );
}
